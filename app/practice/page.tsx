'use client';

import { motion } from 'framer-motion';
import { CheckCircle, Calendar, Home, Sun, Leaf, Moon, Play, Trophy, Menu } from 'lucide-react';
import Link from 'next/link';
import { useEffect, useState } from 'react';

export default function Practice() {
    const [selectedDay, setSelectedDay] = useState(1);
    const [completedTasks, setCompletedTasks] = useState<Record<number, number[]>>({});
    const [completedDays, setCompletedDays] = useState<number[]>([]);
    const [isMenuOpen, setIsMenuOpen] = useState(false);

    useEffect(() => {
        const savedDay = localStorage.getItem('currentDay');
        if (savedDay) setSelectedDay(parseInt(savedDay));

        const savedTasks = localStorage.getItem('practiceCompleted');
        if (savedTasks) setCompletedTasks(JSON.parse(savedTasks));

        const savedCompletedDays = localStorage.getItem('completedFullDays');
        if (savedCompletedDays) setCompletedDays(JSON.parse(savedCompletedDays));
    }, []);

    useEffect(() => {
        localStorage.setItem('currentDay', selectedDay.toString());
        localStorage.setItem('practiceCompleted', JSON.stringify(completedTasks));
        localStorage.setItem('completedFullDays', JSON.stringify(completedDays));
    }, [selectedDay, completedTasks, completedDays]);

    const toggleTask = (day: number, taskIndex: number) => {
        const current = completedTasks[day] || [];
        if (current.includes(taskIndex)) {
            setCompletedTasks({ ...completedTasks, [day]: current.filter(i => i !== taskIndex) });
        } else {
            setCompletedTasks({ ...completedTasks, [day]: [...current, taskIndex] });
        }
    };

    const currentPlan = dailyPlans[selectedDay] || dailyPlans[1];
    const tasks = currentPlan.checklist || [];
    const doneCount = completedTasks[selectedDay]?.length || 0;
    const totalCompletedDays = completedDays.length;

    return (
        <div className="min-h-screen bg-zinc-950 text-white">
            {/* NAV */}
            <nav className="sticky top-0 z-50 glass border-b border-white/10 backdrop-blur-xl">
                <div className="max-w-5xl mx-auto px-6 py-5 flex justify-between items-center">
                    <Link href="/" className="flex items-center gap-3 hover:text-emerald-400 transition">
                        <Home className="w-6 h-6" />
                        <span className="font-medium hidden sm:inline">На главную</span>
                    </Link>

                    <div className="hidden md:flex gap-8 text-sm font-medium">
                        <Link href="/theory" className="hover:text-emerald-400 transition">Теория</Link>
                        <Link href="/practice" className="text-emerald-400">Практика</Link>
                        <Link href="/diary" className="hover:text-emerald-400 transition">Дневник</Link>
                        <Link href="/tools" className="hover:text-emerald-400 transition">Инструменты</Link>
                    </div>

                    <button onClick={() => setIsMenuOpen(!isMenuOpen)} className="md:hidden p-2">
                        <Menu className="w-6 h-6" />
                    </button>
                </div>

                {isMenuOpen && (
                    <div className="md:hidden border-t border-white/10 bg-zinc-950/95 backdrop-blur-xl px-6 py-8 flex flex-col gap-6 text-lg">
                        <Link href="/theory" className="hover:text-emerald-400" onClick={() => setIsMenuOpen(false)}>Теория</Link>
                        <Link href="/practice" className="text-emerald-400" onClick={() => setIsMenuOpen(false)}>Практика</Link>
                        <Link href="/diary" className="hover:text-emerald-400" onClick={() => setIsMenuOpen(false)}>Дневник</Link>
                        <Link href="/tools" className="hover:text-emerald-400" onClick={() => setIsMenuOpen(false)}>Инструменты</Link>
                    </div>
                )}
            </nav>

            {/* Practice Hero — новая версия */}
            <div className="relative h-[460px] md:h-[560px] -mx-6 mb-12 overflow-hidden">
                <img
                    src="/images/morning-light.jpg"
                    alt="Практика"
                    className="absolute inset-0 w-full h-full object-cover object-top md:object-center"
                />
                <div className="absolute inset-0 bg-gradient-to-b from-black/40 via-black/70 to-black/90" />

                <div className="relative z-10 h-full flex items-center justify-center text-center px-6">
                    <div>
                        <Calendar className="w-16 h-16 mx-auto mb-6 text-emerald-400" />
                        <h1 className="text-5xl md:text-6xl font-bold tracking-tighter">Практика</h1>
                        <p className="text-xl text-zinc-400 mt-3">
                            День {selectedDay} из 21 • {currentPlan?.module || 'Модуль 1'}
                        </p>
                    </div>
                </div>
            </div>

            {/* Основной контент */}
            <div className="max-w-4xl mx-auto px-6">

                {/* Календарь */}
                <div className="mb-12 overflow-x-auto pb-4 scrollbar-hide">
                    <div className="flex gap-3 min-w-max">
                        {Array.from({ length: 21 }, (_, i) => i + 1).map((day) => (
                            <button
                                key={day}
                                onClick={() => setSelectedDay(day)}
                                className={`w-12 h-12 md:w-14 md:h-14 rounded-2xl font-semibold transition-all flex-shrink-0 ${day === selectedDay
                                    ? 'bg-emerald-500 text-black scale-110 shadow-lg'
                                    : completedDays.includes(day)
                                        ? 'bg-emerald-600/60 text-emerald-300'
                                        : 'glass hover:bg-white/10'
                                    }`}
                            >
                                {day}
                            </button>
                        ))}
                    </div>
                </div>

                <motion.div
                    initial={{ opacity: 0, y: 20 }}
                    animate={{ opacity: 1, y: 0 }}
                    className="glass p-6 md:p-10 rounded-3xl"
                >
                    <div className="flex flex-col md:flex-row justify-between items-start gap-6 mb-10">
                        <div>
                            <div className="text-emerald-400 text-sm font-medium tracking-widest">{currentPlan.module}</div>
                            <h2 className="text-2xl md:text-3xl font-bold mt-1 leading-tight">{currentPlan.focus}</h2>
                        </div>

                        <div className="text-right shrink-0">
                            <div className="text-sm text-zinc-400">Прогресс дня</div>
                            <div className="text-5xl font-bold text-emerald-400 tabular-nums">
                                {tasks.length > 0 ? Math.round((doneCount / tasks.length) * 100) : 0}%
                            </div>
                        </div>
                    </div>

                    {/* Почему это важно */}
                    <div className="mb-10 p-6 bg-gradient-to-r from-emerald-500/10 to-transparent border-l-4 border-emerald-500 rounded-r-2xl">
                        <p className="text-emerald-400 text-sm font-medium mb-3">ПОЧЕМУ СЕГОДНЯ ЭТО ВАЖНО</p>
                        <p className="text-zinc-300 leading-relaxed text-[17px]">{currentPlan.why}</p>
                    </div>

                    {/* Утро / День / Вечер */}
                    <div className="grid grid-cols-1 md:grid-cols-3 gap-6 mb-12">
                        {[
                            { icon: Sun, label: "УТРО", text: currentPlan.morning },
                            { icon: Leaf, label: "ДЕНЬ", text: currentPlan.day },
                            { icon: Moon, label: "ВЕЧЕР", text: currentPlan.evening }
                        ].map((item, i) => (
                            <div key={i} className="bg-white/5 p-6 rounded-3xl hover:bg-white/10 transition-all border border-white/10">
                                <div className="flex items-center gap-3 text-emerald-400 mb-4">
                                    <item.icon className="w-6 h-6" />
                                    <span className="font-semibold tracking-wider">{item.label}</span>
                                </div>
                                <p className="text-zinc-200 leading-relaxed">{item.text}</p>
                            </div>
                        ))}
                    </div>

                    {/* Чек-лист */}
                    <h3 className="text-2xl font-semibold mb-6 flex items-center gap-3">
                        Чек-лист дня {selectedDay}
                        {doneCount === tasks.length && doneCount > 0 && <Trophy className="w-7 h-7 text-emerald-400" />}
                    </h3>

                    <div className="space-y-4 mb-12">
                        {tasks.map((task: string, index: number) => {
                            const isDone = (completedTasks[selectedDay] || []).includes(index);
                            return (
                                <div
                                    key={index}
                                    onClick={() => toggleTask(selectedDay, index)}
                                    className={`flex items-start gap-4 p-5 md:p-6 rounded-3xl cursor-pointer transition-all border ${isDone
                                        ? 'bg-emerald-500/10 border-emerald-500/30'
                                        : 'glass hover:bg-white/5 border-white/10'
                                        }`}
                                >
                                    <div className={`w-8 h-8 rounded-2xl border-2 flex items-center justify-center flex-shrink-0 mt-0.5 transition-all ${isDone ? 'bg-emerald-500 border-emerald-500' : 'border-white/40'}`}>
                                        {isDone && <CheckCircle className="w-5 h-5 text-black" />}
                                    </div>
                                    <span className={`text-[16px] md:text-[17px] leading-snug ${isDone ? 'line-through text-zinc-400' : 'text-zinc-100'}`}>
                                        {task}
                                    </span>
                                </div>
                            );
                        })}
                    </div>

                    {/* Мотивация */}
                    {doneCount === tasks.length && doneCount > 0 && (
                        <motion.div
                            initial={{ opacity: 0, scale: 0.95 }}
                            animate={{ opacity: 1, scale: 1 }}
                            className="p-8 bg-gradient-to-br from-emerald-500/10 to-teal-500/10 border border-emerald-500/30 rounded-3xl text-center mb-12"
                        >
                            <p className="text-3xl font-semibold text-emerald-400">🎉 День {selectedDay} полностью выполнен!</p>
                            <p className="text-zinc-300 mt-4">Отличная работа. Ты на правильном пути.</p>
                        </motion.div>
                    )}

                    <button
                        onClick={() => window.location.href = '/tools'}
                        className="w-full py-6 md:py-7 bg-gradient-to-r from-emerald-500 via-teal-500 to-cyan-500 text-black rounded-3xl font-semibold text-lg md:text-xl flex items-center justify-center gap-4 hover:scale-[1.02] active:scale-95 transition-all"
                    >
                        <Play className="w-6 h-6" />
                        Открыть инструменты для сегодняшнего дня
                    </button>
                </motion.div>
            </div>
        </div>
    );
}
